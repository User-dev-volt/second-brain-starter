NAMES = ['Pinch hand','Hafter','Carrier','Bookhand','Ground-walker']
BEATS = {
 'Pinch hand':      ['Carrier','Bookhand','Ground-walker'],
 'Hafter':          ['Pinch hand','Ground-walker'],
 'Carrier':         ['Pinch hand','Hafter','Bookhand'],
 'Bookhand':        ['Hafter','Ground-walker'],
 'Ground-walker':   ['Pinch hand','Carrier'],
}
rows=[]
for r in NAMES:
    cells=[]
    for c in NAMES:
        if r==c:
            cells.append('<td class="self">—</td>'); continue
        rb = c in BEATS[r]; cb = r in BEATS[c]
        if rb and cb: cells.append('<td class="both"><span>⇄</span>both</td>')
        elif rb:      cells.append('<td class="win"><span>▲</span>beats</td>')
        elif cb:      cells.append('<td class="loss"><span>▼</span>loses</td>')
        else:         cells.append('<td class="none">·</td>')
    rows.append(f'<tr><th>{r}</th>{"".join(cells)}</tr>')
head = ''.join(f'<th>{n}</th>' for n in NAMES)
open('_g2matrix.html','w').write(
  f'<table class="mx"><thead><tr><th class="corner">beats ↓ / vs →</th>{head}</tr></thead><tbody>{"".join(rows)}</tbody></table>')
